"""Build menu-data.js from Wasabi_All_Menus.xlsx (names, descriptions and options only; NO prices).
Run:  python tools/build_menu_data.py
Edit prices/items in the xlsx (or directly in menu-data.js), then rebuild."""
import json, os, sys
import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
XLSX = os.path.join(HERE, '..', '..', 'Menu', 'Wasabi_All_Menus.xlsx')
OUT = os.path.join(HERE, '..', 'menu-data.js')

def clean(v):
    return '' if v is None else str(v).strip()

def price(v, ptype):
    # Prices are intentionally NOT imported: they will change, and a wrong price must never be published.
    return ''

def build(ws, has_page):
    rows = list(ws.iter_rows(values_only=True))
    hdr = [clean(c) for c in rows[0]]
    idx = {h: i for i, h in enumerate(hdr)}
    cats, order = {}, []
    for r in rows[1:]:
        if not any(c is not None for c in r):
            continue
        cat = clean(r[idx['Category']]); name = clean(r[idx['Menu Item']])
        jp = clean(r[idx['Japanese Name']]); opt = clean(r[idx['Option / Size']])
        desc = clean(r[idx['Description']]); p = price(r[idx['Current Price']], '')
        if cat not in cats:
            cats[cat] = []; order.append(cat)
        items = cats[cat]
        it = next((x for x in items if x['n'] == name), None)
        if it is None:
            it = {'n': name, 'jp': jp, 'd': desc, 'p': []}
            items.append(it)
        else:
            if jp != it['jp']: it['jp'] = ''
            if desc != it['d'] and desc: it['d'] = it['d'] or desc
        it['p'].append({'l': opt, 'v': p})
    return [{'name': c, 'items': cats[c]} for c in order]

wb = openpyxl.load_workbook(XLSX, data_only=True)
data = {'dinner': build(wb['Dinner Menu'], True), 'lunch': build(wb['Lunch Menu'], False)}
with open(OUT, 'w', encoding='utf8') as f:
    f.write('// Generated by tools/build_menu_data.py. Edit the xlsx and rebuild, or edit here directly.\n')
    f.write('window.WASABI_MENU = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
print({k: (len(v), sum(len(c['items']) for c in v)) for k, v in data.items()})
